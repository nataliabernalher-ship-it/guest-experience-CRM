export function OutcomeMark({ rejected }: { rejected: boolean }) {
  return (
    <span
      className={rejected ? "mark mark-rejected" : "mark mark-done"}
      role="img"
      aria-label={rejected ? "Rejected" : "Done"}
    >
      {rejected ? (
        <svg viewBox="0 0 20 20" aria-hidden="true">
          <circle cx="10" cy="10" r="10" />
          <path d="M6.5 6.5 13.5 13.5 M13.5 6.5 6.5 13.5" />
        </svg>
      ) : (
        <svg viewBox="0 0 20 20" aria-hidden="true">
          <circle cx="10" cy="10" r="10" />
          <path d="M5.5 10.2 8.4 13.1 14.5 6.8" />
        </svg>
      )}
    </span>
  );
}
